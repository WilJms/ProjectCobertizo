"""Original deterministic, unlit material maps. No photo lighting is baked into albedo."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFilter
import numpy as np
import math, json
R=Path(__file__).resolve().parents[1]; O=R/'blender/textures'; O.mkdir(parents=True,exist_ok=True)
rng=np.random.default_rng(7321); N=1024
Y,X=np.mgrid[0:N,0:N]/N

def noise(size, amplitude=1):
 a=Image.fromarray(np.uint8(rng.random((size,size))*255)).resize((N,N),Image.Resampling.BICUBIC)
 return (np.array(a)/255-.5)*amplitude

def save(name,col,h,strength=2):
 col=np.clip(col,0,255).astype('uint8'); Image.fromarray(col).save(O/f'{name}_color.jpg',quality=95)
 dy,dx=np.gradient(h); n=np.stack([-dx*strength,-dy*strength,np.ones_like(h)],axis=-1); n/=np.linalg.norm(n,axis=-1)[...,None]
 Image.fromarray(np.uint8((n*.5+.5)*255)).save(O/f'{name}_normal.png')
 Image.fromarray(np.uint8(np.clip(.68+noise(90,.12),0,1)*255)).save(O/f'{name}_roughness.png')

for name,base in [('wood_new',[151,96,49]),('wood_old',[113,77,45])]:
 warp=noise(6,.021)+noise(19,.006)
 # Grain follows U (horizontal length). Knots bend the grain without lighting.
 phase=(Y+warp)*270
 for kx,ky in [(0.23,.4),(.71,.8)]:
  q=((X-kx)/.10)**2+((Y-ky)/.07)**2
  phase+=3*np.exp(-q*1.5)
 g=(np.sin(phase*math.pi)+np.sin(phase*math.pi*3.6)*.26)*6+noise(100,8)+noise(12,18)
 col=np.array(base)[None,None,:]+g[...,None]*np.array([1,.80,.57])
 save(name,col,g/100,1.4)

base=Image.new('RGB',(N,N),(139,133,122)); h=Image.new('L',(N,N),95); d=ImageDraw.Draw(base); hd=ImageDraw.Draw(h)
for i in range(18500):
 x,y=rng.integers(-5,N+5,2); w,hh=rng.integers(3,11,2); tone=rng.choice([.46,.62,.8,1,1.1,1.23])
 c=tuple(int(v*tone) for v in [163,153,139]); box=[int(x),int(y),int(x+w),int(y+hh)]
 d.ellipse(box,fill=c); hd.ellipse(box,fill=int(130+tone*40))
col=np.array(base).astype(float)+noise(170,12)[...,None]; save('aggregate',col,np.array(h)/255,8)
for name,base,strength in [('stucco_blue',[18,64,101],5),('coping',[184,174,145],4),('concrete',[113,117,113],3),('fabric_red',[172,19,33],1),('fabric_grey',[67,72,77],1)]:
 fine=noise(200,20)+noise(90,15)+noise(19,6)
 if 'fabric' in name: fine+=3*np.sin(X*N*3)*np.sin(Y*N*3)
 save(name,np.array(base)[None,None,:]+fine[...,None],fine/70,strength)
for name,base in [('grass',[65,88,32]),('artificial',[43,87,50])]:
 coarse=noise(6,24)+noise(20,24)
 col=np.clip(np.array(base)[None,None,:]+coarse[...,None]*np.array([.9,1,.35]),0,255).astype('uint8')
 im=Image.fromarray(col); d=ImageDraw.Draw(im)
 for _ in range(140000):
  x,y=rng.integers(0,N,2); shade=rng.uniform(.65,1.55)
  c=tuple(int(np.clip(v*shade,0,255)) for v in base)
  d.line((int(x),int(y),int(x+rng.integers(-4,5)),int(y-rng.integers(2,11))),fill=c,width=1)
 save(name,np.array(im),np.array(im).mean(-1)/255,2.5)
# Night keeps its original subtle variation. Day uses a cloudless blue gradient.
# Both engines read the same images; the physical direct sun lives in the master.
W,H=2048,1024
cloud=(noise(7,1)+noise(20,.6)+noise(45,.25))
cloud=Image.fromarray(np.uint8(np.clip(cloud+.5,0,1)*255)).resize((W,H))
c=np.array(cloud)/255; v=np.linspace(0,1,H)[:,None,None]
from make_day_sky import make_day_sky
make_day_sky(O/'sky_day.jpg')
colors=np.zeros((H,W,3))+np.array([.045,.060,.10]); colors=colors*(.85+c[...,None]*.30)
Image.fromarray(np.uint8(np.clip(colors,0,1)*255)).save(O/'sky_night.jpg',quality=95)
(O/'LICENSE.txt').write_text('All textures in this directory are original deterministic procedural assets generated by tools/make_textures.py and tools/make_day_sky.py for this project. No third-party photographs or stock assets. Seed 7321. Generated assets may be used and modified with the project.\n')
print('Generated',len(list(O.iterdir())),'material/environment files')
